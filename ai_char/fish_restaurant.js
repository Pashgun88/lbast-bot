async function dumpLinks(page) {
  return page.locator('a').evaluateAll((els) =>
    els.map((e) => ({ t: e.textContent.trim(), href: e.getAttribute('href') })).filter((x) => x.t)
  );
}

async function runPath(page, steps) {
  for (let i = 0; i < steps.length; i++) {
    const step = steps[i];
    const text = await getBodyText(page);
    console.log(`\n--- step ${i + 1}/${steps.length}: ${JSON.stringify(step)} ---`);
    console.log(text.slice(0, 400));

    if (typeof step === 'object' && step.fight) {
      for (let f = 0; f < (step.times || 1); f++) {
        const won = await fightLoop(page).catch((e) => {
          console.log('fightLoop error:', e.message);
          return null;
        });
        console.log(`fightLoop (${f + 1}/${step.times || 1}) result:`, won);
        if (!won) {
          console.log('ОСТАНОВКА: бой не удался/не найден, разбираться вручную.');
          return false;
        }
      }
      continue;
    }

    const ok = await clickByTexts(page, [step], step);
    if (!ok) {
      console.log(`ОСТАНОВКА: не нашёл ссылку, содержащую "${step}". Ссылки на странице:`);
      console.log(JSON.stringify(await dumpLinks(page), null, 2));
      return false;
    }
    await new Promise((r) => setTimeout(r, 900));
  }
  console.log('\nПуть пройден полностью (или до последнего описанного шага).');
  return true;
}

(async () => {
  const steps = PATHS[FISH_PATH];
  if (!steps) {
    console.log(`Неизвестный FISH_PATH="${FISH_PATH}". Доступные:`, Object.keys(PATHS).join(', '));
    process.exit(1);
  }

  const userDataDir = path.join(__dirname, 'chrome-profile-ai-char');
  const context = await chromium.launchPersistentContext(userDataDir, { headless: false, viewport: null });
  const page = context.pages()[0] || (await context.newPage());

  await page.goto('http://lbast.ru/', { waitUntil: 'domcontentloaded', timeout: 60000 });
  const loginInput = page.locator('input[name="login"]');
  if ((await loginInput.count().catch(() => 0)) > 0) {
    await loginInput.fill(LOGIN);
    await page.locator('input[name="password"]').fill(PASS);
    await page.locator('input[type="submit"]').first().click();
    await page.waitForLoadState('domcontentloaded').catch(() => {});
  }

  await page.goto('http://lbast.ru/location.php', { waitUntil: 'domcontentloaded', timeout: 60000 });

  console.log(`===== Рыбный ресторан: путь "${FISH_PATH}" (${steps.length} шагов) =====`);
  await runPath(page, steps);

  console.log('\nKEEP OPEN');
  await new Promise(() => {});
})();
