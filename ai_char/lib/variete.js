const FIGHT_TEXTS = ['в бой'];
const CONTINUE_TEXTS = ['продолжить квест', 'далее'];
const DONE_RE = /(Задание завершено|Задание выполнено|Квест выполнен)/i;
const MAX_SCREENS = 80;

// Взятый квест исчезает из Q-меню, поэтому одного «есть в меню» для запуска мало: начатую и
// недоведённую сцену надо продолжать. Флаг живёт в памяти процесса - этого хватает: после
// перезапуска драйвера сцена всё равно ждёт на «Продолжить квест», а квест вернётся в меню.
let varieteStarted = false;
function varieteNeedsResume() { return varieteStarted; }

// Ссылки экрана без служебной обвязки сайта.
const CHROME = new Set(['обновить', 'чат', 'в игру', 'форум', 'жг', 'галерея', 'кланы', 'карта',
  'бои', 'кто здесь?', 'выход', 'размер текста', 'амулет | конь', 'амулет', 'aмулет', 'конь',
  'инвентарь', 'письма', 'дневник', 'анкета', 'доступные квесты', 'группа бойцов']);

async function screenLinks(page) {
  return page.evaluate(() => Array.from(document.querySelectorAll('a'))
    .map((a) => ({ t: (a.innerText || '').trim(), h: a.getAttribute('href') || '' }))
    .filter((x) => x.t && x.h)).catch(() => []);
}

const norm = (s) => String(s || '').toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ').trim();

// used: реплики, которые уже нажимали. Диалог линейный, каждая реплика нужна один раз, а ссылки
// локаций («Таверна «Три поросенка»») висят на экране и дальше - без этого проход зациклился:
// Таверна -> Зал варьете -> снова Таверна, восемьдесят экранов подряд (живьём 24.09.2026).
function findOption(links, needles, used) {
  for (const needle of needles) {
    if (used && used.has(needle)) continue;
    const n = norm(needle);
    const hit = links.find((l) => !CHROME.has(norm(l.t)) && norm(l.t).includes(n));
    if (hit) return { hit, needle };
  }
  return null;
}

async function progressVarieteQuest(page, { questCount } = {}) {
  // Свежий заход: [инфо] -> «Выполнение». Если квест уже взят и сцена на середине, в меню его
  // нет - тогда заходим через «Продолжить квест» с локации.
  if (await existsAnyText(page, [QUEST])) {
    if (!(await clickInfoForQuest(page, QUEST))) {
      console.log('Варьете: не удалось открыть инфо квеста.');
      return false;
    }
    await tryPerformStepOptional(page, {
      stepName: 'Выполнение',
      currentTexts: ['Выполнение', 'выполнение', 'К месту выполнения', 'к месту выполнения'],
      waitAfterClickMs: 3000,
    });
    await waitOutHorseTravel(page, page.url());
    await pause(page, 700, 1300);
    // Телепорт к таверне - один раз и явно: «Амулет» -> пункт списка с «Три поросенка».
    // В самом проходе «Амулет» не трогаем (см. VARIETE_OPTIONS).
    await clickByTexts(page, ['Амулет', 'Aмулет'], 'Варьете: Амулет').catch(() => {});
    await pause(page, 700, 1300);
    const tp = (await screenLinks(page)).find((l) => norm(l.t).includes('три поросенка'));
    if (tp) {
      console.log(`Варьете: телепорт - ${tp.t}`);
      await page.goto(new URL(tp.h, page.url()).href, { waitUntil: 'domcontentloaded', timeout: 60000 });
      await waitOutHorseTravel(page, page.url());
      await pause(page, 700, 1300);
    } else {
      console.log('Варьете: в списке амулета нет «Три поросенка» - иду по экрану как есть.');
    }
    varieteStarted = true;
  }

  const used = new Set();
  let fights = 0;
  let idle = 0;
  // Защита от хождения по кругу. Считаем, сколько раз КАЖДЫЙ экран встретился за проход, а не
  // сколько раз подряд: 07.10.2026 проход 80 экранов мотало по кольцу из ДВУХ экранов (экран
  // выбора -> нет нужной реплики -> перечитать локацию -> «Продолжить квест» -> снова экран
  // выбора), и проверка «тот же экран подряд» ни разу не сработала, потому что экраны
  // чередовались. В логе это выглядело как 80 строк «Продолжить квест (продолжение)».
  const seenTimes = new Map();
  for (let i = 0; i < MAX_SCREENS; i++) {
    const text = await getBodyText(page);
    if (i > 0 && i % 10 === 0) {
      const seen = await screenLinks(page);
      console.log(`Варьете: экран ${i}, ссылки: ${seen.map((l) => l.t).join(' | ').slice(0, 300)}`);
    }
    if (DONE_RE.test(text)) {
      console.log(`Варьете: квест завершён (боёв ${fights}).`);
      varieteStarted = false;
      await clickByTexts(page, ['В игру', 'в игру'], 'В игру (after Варьете)').catch(() => {});
      return true;
    }
    const links = await screenLinks(page);
    // В подпись экрана входит и текст: подряд идущие «Далее» ведут по разным виньеткам с одним
    // и тем же набором ссылок, и по одним ссылкам они выглядят как один и тот же экран.
    // Часы в шапке сайта идут каждую секунду, поэтому из текста они вырезаются: иначе один и тот
    // же экран каждый раз даёт новую подпись, и никакая защита от кольца не срабатывает.
    const body = text.replace(/\d{1,2}:\d{2}(:\d{2})?/g, '').replace(/\s+/g, ' ').slice(0, 200);
    const signature = `${links.map((l) => l.t).join('|')}##${body}`;
    const times = (seenTimes.get(signature) || 0) + 1;
    seenTimes.set(signature, times);
    if (times >= 4) {
      console.log(`Варьете: экран встретился ${times} раз - значит иду по кругу, нужной реплики в списке нет.`);
      console.log(`Варьете: ссылки экрана: ${links.map((l) => l.t).join(' | ').slice(0, 800)}`);
      return false;
    }

    const option = findOption(links, VARIETE_OPTIONS, used);
    if (option) {
      idle = 0;
      used.add(option.needle);
      console.log(`Варьете: ${option.hit.t.slice(0, 60)}`);
      await page.goto(new URL(option.hit.h, page.url()).href, { waitUntil: 'domcontentloaded', timeout: 60000 });
      await waitOutHorseTravel(page, page.url());
      await pause(page, 700, 1300);
      continue;
    }

    const fight = findOption(links, FIGHT_TEXTS);  // бой может повториться - не помечаем
    if (fight) {
      if (!(await questFightHpGate(page, `Варьете (бой ${fights + 1})`, QUEST_FIGHT_HP_FLOOR, { waitForRecovery: true }))) {
        console.log('Варьете: мало HP перед боем - остаюсь в сцене, продолжу в следующем круге.');
        return false;
      }
      console.log(`Варьете: бой ${fights + 1}`);
      await page.goto(new URL(fight.hit.h, page.url()).href, { waitUntil: 'domcontentloaded', timeout: 60000 });
      await fightLoop(page);
      fights += 1;
      await pause(page, 800, 1500);
      continue;
    }

    const cont = findOption(links, CONTINUE_TEXTS); // «Далее» повторяется много раз подряд
    if (cont) {
      idle = 0;
      // Логируем и «Далее»: без этого проход 80 экранов молчал в логе, и было не понять, что он
      // жмёт по кругу (24.09.2026).
      console.log(`Варьете: ${cont.hit.t.slice(0, 40)} (продолжение)`);
      await page.goto(new URL(cont.hit.h, page.url()).href, { waitUntil: 'domcontentloaded', timeout: 60000 });
      await pause(page, 700, 1300);
      continue;
    }

    if (idle === 0) {
      idle = 1; // сцена могла ещё не проявиться - перечитаем локацию один раз
      await page.goto('http://lbast.ru/location.php', { waitUntil: 'domcontentloaded', timeout: 60000 });
      await pause(page, 900, 1500);
      continue;
    }
    console.log(`Варьете: на экране нет ни реплики, ни боя, ни продолжения (боёв ${fights}).`);
    console.log(`Варьете: ссылки экрана: ${links.map((l) => l.t).join(' | ').slice(0, 400)}`);
    return false;
  }
  console.log(`Варьете: ${MAX_SCREENS} экранов подряд без завершения - выхожу, продолжу в следующем круге.`);
  return false;
}
